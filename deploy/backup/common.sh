#!/usr/bin/env bash
# Helpers sourced by the backup/restore entry points. COMPOSE_CMD is a whitespace-separated
# argument list (no shell evaluation). Use paths without whitespace in this interface.
backup_setup() {
	: "${COMPOSE_CMD:?defina COMPOSE_CMD}"
	: "${BACKUP_INSTALLATION:?defina BACKUP_INSTALLATION (identidade única da instalação)}"
	read -r -a compose <<<"$COMPOSE_CMD"
	installation=$BACKUP_INSTALLATION
	[[ "$installation" =~ ^[a-zA-Z0-9_.:-]+$ ]] || { echo 'BACKUP_INSTALLATION inválido' >&2; exit 2; }
	mirror=/mirror
	umask 077
	work_tmp=$(mktemp -d /tmp/.chatisp-backup.XXXXXX)
	operation_locked=0
}

in_mirror() { "${compose[@]}" run --rm -T --no-deps -u 0 "$@"; }
sql() { "${compose[@]}" exec -T postgres psql -U chatisp -d chatisp -v ON_ERROR_STOP=1 -At "$@"; }

acquire_operation_lock() {
	# Shared destination lock, including between hosts. A SIGKILL may leave it behind; refuse
	# subsequent operations until an operator establishes that no operation is still running.
	in_mirror --entrypoint sh chatisp-migrate -c '
		set -eu
		[ ! -L /mirror ] && [ ! -L /mirror/.operation-lock ]
		mkdir /mirror/.operation-lock || { echo "backup/restore concorrente ou lock de operação interrompida; examine /mirror/.operation-lock" >&2; exit 1; }
	'
	operation_locked=1
}

backup_cleanup() {
	local status=$?
	if [ "$operation_locked" = 1 ]; then
		in_mirror --entrypoint rmdir chatisp-migrate /mirror/.operation-lock >/dev/null || status=1
	fi
	rm -rf "$work_tmp"
	exit "$status"
}

publish_artifact() { # local file, relative destination (generated by these scripts)
	local source=$1 target=$2 checksum
	checksum=$(sha256sum <"$source" | cut -d' ' -f1)
	# Producer is already complete before publication. An interruption between the two links
	# leaves an explicitly incomplete artifact that restore refuses instead of ignoring it.
	in_mirror --entrypoint sh chatisp-migrate -c '
		set -eu -C
		target=$1; checksum=$2; dir=${target%/*}
		[ ! -L /mirror ] && [ ! -L "$dir" ]
		mkdir -p "$dir"
		[ ! -L "$target" ] && [ ! -L "$target.sha256" ]
		cat > "$target.partial"
		actual=$(sha256sum < "$target.partial"); actual=${actual%% *}
		[ "$actual" = "$checksum" ] || { echo "artefato incompleto" >&2; exit 1; }
		chmod 400 "$target.partial"
		ln "$target.partial" "$target"
		printf "%s\n" "$checksum" > "$target.sha256.partial"
		chmod 400 "$target.sha256.partial"
		ln "$target.sha256.partial" "$target.sha256"
		rm "$target.partial" "$target.sha256.partial"
	' artifact "$mirror/$target" "$checksum" <"$source"
}
